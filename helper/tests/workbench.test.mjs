import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import sharp from 'sharp';
const dir = fs.mkdtempSync(path.join(os.tmpdir(),'psai-workbench-'));
process.env.PS_AI_BRIDGE_DATA_DIR=dir;
const {config}=await import('../lib/config.mjs'); config.outputDir=path.join(dir,'outputs');
const jobs=await import('../lib/jobs.mjs');
const {createWorkbench}=await import('../lib/workbench.mjs');
const buffer=await sharp({create:{width:24,height:32,channels:4,background:{r:100,g:120,b:140,alpha:.5}}}).png().toBuffer();
let calls=0;
const provider={async run(j){calls++;const p=path.join(j.dir,'generated.png');fs.writeFileSync(p,buffer);return {path:p,width:24,height:32};}};
const context={providers:{fake:provider},capabilities:{fake:{aspects:['1:1','3:4']}}};
let wb=createWorkbench(context);
const post=(p,b={})=>wb.route('POST',p.split('/'),b);
const uploaded=()=>jobs.saveUpload(buffer,'image/png');
test('batch is durable, initially paused, does not duplicate a finished item, survives restart',async()=>{
 const b=await post('batches',{title:'test',inputs:[{uploadId:uploaded(),name:'one'},{uploadId:uploaded(),name:'two'}],options:{provider:'fake',prompt:'edit',aspect:'auto',post:{align:false,cc:'none'}}});
 await wb.tick();assert.equal(calls,0);
 await post(`batches/${b.id}/start`);await wb.tick();
 for(let i=0;i<100 && jobs.listJobs()[0]?.status!=='done';i++)await new Promise(r=>setTimeout(r,10));
 assert.equal(calls,1);
 await post(`batches/${b.id}/pause`);await wb.tick();assert.equal(calls,1);
 wb.close();wb=createWorkbench(context);
 await wb.tick();assert.equal(calls,1);
 await post(`batches/${b.id}/start`);await wb.tick();
 for(let i=0;i<100 && jobs.listJobs().some(j=>j.status==='running');i++)await new Promise(r=>setTimeout(r,10));
 await wb.tick();assert.equal(calls,2);
 const state=(await wb.route('GET',['batches'])).batches.find(x=>x.id===b.id);
 assert.equal(state.status,'done');assert.ok(state.items.every(x=>x.aspect==='3:4'));
});
test('tool preview preserves alpha, save uses identical pixels and repeated save is idempotent',async()=>{
 const p=await post('tools/preview',{uploadId:uploaded(),exposure:.5,saturation:.8,glow:.2});
 const preview=fs.readFileSync(jobs.useUpload(p.uploadId));
 assert.equal((await sharp(preview).metadata()).hasAlpha,true);
 const j=await post('tools/save-preview',{previewId:p.previewId});
 assert.deepEqual(fs.readFileSync(j.result.path),preview);
 const again=await post('tools/save-preview',{previewId:p.previewId});assert.equal(j.id,again.id);
 const scopes=await post('tools/scopes',{jobId:j.id});assert.equal(scopes.histogram[0].reduce((a,b)=>a+b,0),24*32);
 for(const channel of scopes.parade)assert.equal(channel.flat().reduce((a,b)=>a+b,0),24*32);
 assert.equal(scopes.vectorscope.flat().reduce((a,b)=>a+b,0),24*32);
 const applied=await jobs.recordPlacement(j,{variant:{cc:'none',tex:false,t:1},docId:7,docName:'test.psd',layerId:3});
 assert.deepEqual(jobs.appliedVariant(j),applied.variant);
 const persisted=JSON.parse(fs.readFileSync(path.join(j.dir,'job.json')));assert.equal(persisted.applied.id,applied.id);
 await assert.rejects(()=>jobs.recordPlacement(j,{variant:{t:NaN}}),/强度/);
});
test('neutral sRGB samples fall at vectorscope centre; original-size import is lossless PNG',async()=>{
 const neutral=await sharp({create:{width:5000,height:8,channels:3,background:{r:128,g:128,b:128}}}).png().toBuffer();
 const id=jobs.saveUpload(neutral,'image/png');const d=await post('tools/scopes',{uploadId:id});
 assert.equal(d.vectorscope[64][64],d.width*d.height);
 const {normalizeImage}=await import('../lib/image.mjs');const imported=await normalizeImage(jobs.useUpload(id),0);
 assert.equal(imported.width,5000);assert.equal(imported.height,8);assert.equal(imported.mime,'image/png');
});
test.after(()=>{wb.close();fs.rmSync(dir,{recursive:true,force:true});});
