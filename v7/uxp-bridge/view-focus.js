'use strict';

// Read-only navigation helper for AI-retouch-trace candidates.
//
// This action is deliberately separate from ps.seam.apply.  It may select a
// document and move Photoshop's view, but it must never touch pixels, layers,
// selection, visibility, or history.  Photoshop does not expose a stable
// writable View DOM object on every supported host, so this module probes the
// capability and fails closed when the host cannot prove the requested view
// change.

const { matrix, inverse, point } = require('./assistant-view-geometry');

const MAX_CANDIDATE_ID = 240;
const MAX_DOC_NAME = 512;
const MIN_ZOOM = 5;
const MAX_ZOOM = 3200;

function failure(code, message, raw) {
  const error = new Error(message || code);
  error.code = code;
  if (raw !== undefined) error.raw = raw;
  return error;
}

function finite(value) { return typeof value === 'number' && Number.isFinite(value); }
function safeInteger(value) { return Number.isSafeInteger(value) ? value : null; }
function numeric(value) {
  const number = Number(value);
  return Number.isFinite(number) ? number : null;
}

function documentById(app, docId) {
  const documents = app && app.documents;
  if (documents && Number.isFinite(Number(documents.length))) {
    for (let index = 0; index < documents.length; index++) {
      const document = documents[index];
      if (document && Number(document.id) === Number(docId)) return document;
    }
  }
  try { if (app && app.activeDocument && Number(app.activeDocument.id) === Number(docId)) return app.activeDocument; } catch (_) {}
  return null;
}

function historyId(doc) {
  try {
    const value = doc && doc.activeHistoryState && doc.activeHistoryState.id;
    return safeInteger(Number(value));
  } catch (_) { return null; }
}

function dimensions(doc) {
  try {
    const width = safeInteger(Number(doc.width));
    const height = safeInteger(Number(doc.height));
    return width > 0 && height > 0 ? { width, height } : null;
  } catch (_) { return null; }
}

function rectangle(value, width, height) {
  if (!value) return null;
  let left = Number(value.left), top = Number(value.top), right = Number(value.right), bottom = Number(value.bottom);
  if (![left, top, right, bottom].every(Number.isFinite)) {
    const x = Number(value.x), y = Number(value.y), w = Number(value.width), h = Number(value.height);
    if (![x, y, w, h].every(Number.isFinite)) return null;
    left = x; top = y; right = x + w; bottom = y + h;
  }
  if (!(right > left && bottom > top)) return null;
  if (width != null && height != null && (left < 0 || top < 0 || right > width || bottom > height)) return null;
  const result = { left: Math.floor(left), top: Math.floor(top), right: Math.ceil(right), bottom: Math.ceil(bottom) };
  result.width = result.right - result.left; result.height = result.bottom - result.top;
  result.center = { x: (result.left + result.right) / 2, y: (result.top + result.bottom) / 2 };
  return result.width > 0 && result.height > 0 ? result : null;
}

function normalizeRect(value, width, height) {
  const result = rectangle(value, width, height);
  if (!result) throw failure('VIEW_FOCUS_REGION_INVALID', '候选定位区域无效或超出画布');
  return result;
}

function candidateId(value) {
  const text = String(value == null ? '' : value);
  // IDs are generated by the desktop run and are never evaluated as code.
  // Keep separators used by the existing reviewItems IDs while rejecting
  // whitespace/control characters and unbounded input.
  return /^[A-Za-z0-9][A-Za-z0-9._:-]{0,239}$/.test(text) ? text : null;
}

// These reads are deliberately defensive.  Photoshop UXP collections are
// array-like and some hosts do not expose the selection channel reliably.  A
// missing read becomes `null` evidence, while a confirmed change fails the
// operation closed.
function activeLayerIds(doc) {
  const ids = [];
  try {
    const layers = doc && doc.activeLayers;
    for (let index = 0; layers && index < Number(layers.length || 0); index++) {
      const id = safeInteger(Number(layers[index] && layers[index].id));
      if (id !== null) ids.push(id);
    }
  } catch (_) {}
  return ids;
}

async function selectionRect(app, docId) {
  try {
    if (!app || typeof app.batchPlay !== 'function') return { available: false, value: null };
    const rows = await app.batchPlay([{
      _obj: 'get',
      _target: [{ _property: 'selection' }, { _ref: 'document', _id: docId }]
    }], { synchronousExecution: true });
    const row = rows && rows[0];
    if (!row || row._obj === 'error') return { available: false, value: null };
    const bounds = row.selection;
    if (!bounds) return { available: true, value: null };
    const value = key => Number(bounds[key] && typeof bounds[key] === 'object' && '_value' in bounds[key] ? bounds[key]._value : bounds[key]);
    const left = value('left'), top = value('top'), right = value('right'), bottom = value('bottom');
    if (![left, top, right, bottom].every(Number.isFinite) || right <= left || bottom <= top) return { available: true, value: null };
    return { available: true, value: { left, top, right, bottom } };
  } catch (_) { return { available: false, value: null }; }
}

function sameRect(a, b) {
  if (!a || !b) return a === b;
  return ['left', 'top', 'right', 'bottom'].every(key => Number(a[key]) === Number(b[key]));
}

function equalIds(a, b) {
  return Array.isArray(a) && Array.isArray(b) && a.length === b.length && a.every((id, index) => id === b[index]);
}

async function guardState(app, doc, docId) {
  const current = app && app.activeDocument;
  return {
    activeDocumentId: safeInteger(Number(current && current.id)),
    activeDocumentBound: Number(current && current.id) === Number(docId),
    historyId: historyId(current || doc),
    layerIds: activeLayerIds(current || doc),
    selectionState: await selectionRect(app, docId),
    dimensions: dimensions(current || doc)
  };
}

function normalizeMode(value) {
  const mode = String(value == null ? 'fit-target' : value);
  if (mode === 'fit' || mode === 'fit-target') return 'fit-target';
  if (mode === 'current') return 'current';
  if (mode === 'zoom-in') return 'zoom-in';
  return 'fit-target';
}

function normalizeParams(params, nowValue) {
  const p = params || {};
  const id = candidateId(p.candidateId);
  if (!id) throw failure('VIEW_FOCUS_PARAMS', '缺少或无效的候选定位 ID');
  const docId = safeInteger(Number(p.docId));
  if (!(docId > 0)) throw failure('VIEW_FOCUS_PARAMS', '候选定位缺少有效的 Photoshop 文档 ID');
  const docName = String(p.docName == null ? '' : p.docName);
  if (!docName || docName.length > MAX_DOC_NAME) throw failure('VIEW_FOCUS_PARAMS', '候选定位缺少有效的文档名称');
  const docWidth = safeInteger(Number(p.docWidth)), docHeight = safeInteger(Number(p.docHeight));
  if (!(docWidth > 0 && docHeight > 0)) throw failure('VIEW_FOCUS_PARAMS', '候选定位缺少有效的画布尺寸');
  const region = normalizeRect(p.region, docWidth, docHeight);
  if (p.expiresAt == null || !finite(Number(p.expiresAt))) throw failure('VIEW_FOCUS_PARAMS', '候选定位请求缺少有效期限');
  if (Number(p.expiresAt) <= Number(nowValue)) throw failure('VIEW_FOCUS_EXPIRED', '候选定位请求已过期，请重新执行 AI 修图痕迹检测');
  const suppliedHistory = p.historyId != null ? p.historyId : (p.activeHistoryStateId != null ? p.activeHistoryStateId : p.docHistoryId);
  const history = suppliedHistory == null ? null : safeInteger(Number(suppliedHistory));
  if (suppliedHistory != null && !(history > 0)) throw failure('VIEW_FOCUS_PARAMS', '候选定位的文档版本无效');
  const mode = normalizeMode(p.mode);
  return { candidateId: id, docId, docName, docWidth, docHeight, region,
    historyId: history, expiresAt: Number(p.expiresAt), mode,
    selectAnnotationLayer: p.selectAnnotationLayer === true };
}

function currentZoom(doc) {
  try {
    const zoom = Number(doc && doc.zoom);
    return Number.isFinite(zoom) && zoom > 0 ? zoom : null;
  } catch (_) { return null; }
}

function clampZoom(value) { return Math.max(MIN_ZOOM, Math.min(MAX_ZOOM, Math.round(value * 100) / 100)); }

function regionCenter(region) { return { x: (region.left + region.right) / 2, y: (region.top + region.bottom) / 2 }; }

function normalizeView(view) {
  return view && (typeof view === 'object' || typeof view === 'function') ? view : null;
}

function getView(doc, app) {
  // Keep this list intentionally small. These are the documented/observed
  // names used by different Photoshop UXP builds; unknown objects are ignored.
  try { if (doc && doc.activeView) return normalizeView(doc.activeView); } catch (_) {}
  try { if (doc && doc.view) return normalizeView(doc.view); } catch (_) {}
  try { if (app && app.activeView) return normalizeView(app.activeView); } catch (_) {}
  return null;
}

function readDomView(view) {
  if (!view) return null;
  let zoom = null, center = null;
  try {
    const value = Number(view.zoom);
    if (Number.isFinite(value) && value > 0) zoom = value;
  } catch (_) {}
  try {
    const value = view.center || view.centerPoint;
    if (value && finite(Number(value.x)) && finite(Number(value.y))) center = { x: Number(value.x), y: Number(value.y) };
    else if (Array.isArray(value) && finite(Number(value[0])) && finite(Number(value[1]))) center = { x: Number(value[0]), y: Number(value[1]) };
  } catch (_) {}
  return zoom !== null || center ? { zoom, center } : null;
}

function nativeViewRead(app, docId) {
  if (!app || typeof app.batchPlay !== 'function') return Promise.resolve(null);
  return Promise.resolve().then(async () => {
    try {
      const rows = await app.batchPlay([{ _obj: 'multiGet', _target: { _ref: 'document', _id: docId },
        extendedReference: [['documentID', 'viewInfo', 'viewTransform', 'width', 'height']] }], { synchronousExecution: true });
      const row = rows && rows[0];
      if (!row || row._obj === 'error') return null;
      return { documentID: row.documentID, viewTransform: matrix(row.viewTransform), viewInfo: row.viewInfo || null };
    } catch (_) { return null; }
  });
}

function viewportCenter(row) {
  const bounds = row && row.viewInfo && row.viewInfo.activeView && row.viewInfo.activeView.globalBounds;
  if (!bounds || !finite(Number(bounds.left)) || !finite(Number(bounds.right)) || !finite(Number(bounds.top)) || !finite(Number(bounds.bottom))) return null;
  const transform = inverse(row.viewTransform);
  if (!transform) return null;
  return point(transform, { x: (Number(bounds.left) + Number(bounds.right)) / 2, y: (Number(bounds.top) + Number(bounds.bottom)) / 2 });
}

function closeEnough(a, b, tolerance) { return a && b && Math.abs(a.x - b.x) <= tolerance && Math.abs(a.y - b.y) <= tolerance; }

function desiredZoom(viewOrOptions, regionArg, modeArg) {
  // Public pure helper form used by tests and by the desktop panel.
  if (viewOrOptions && Object.prototype.hasOwnProperty.call(viewOrOptions, 'zoomPercent')) {
    const viewport = viewOrOptions, region = regionArg || {}, mode = normalizeMode(modeArg);
    const current = Number(viewport.zoomPercent) > 0 ? Number(viewport.zoomPercent) : 100;
    if (mode === 'current') return current;
    if (mode === 'zoom-in') return current * 2;
    const bounds = viewport.bounds;
    if (!bounds) return current;
    const width = Number(bounds.right) - Number(bounds.left), height = Number(bounds.bottom) - Number(bounds.top);
    const factor = Math.min(width / (Number(region.width) * 1.35), height / (Number(region.height) * 1.35));
    return current * (Number.isFinite(factor) && factor > 0 ? factor : 1);
  }
  const { doc, row, region, mode: requestedMode } = viewOrOptions || {};
  const mode = normalizeMode(requestedMode);
  const existing = currentZoom(doc) || 100;
  if (mode === 'current') return clampZoom(existing);
  if (mode === 'zoom-in') return clampZoom(existing * 2);
  const bounds = row && row.viewInfo && row.viewInfo.activeView && row.viewInfo.activeView.globalBounds;
  // Without viewport geometry, preserve the current zoom. Centering is still
  // useful and avoids guessing a zoom value on hosts that hide their viewport.
  if (!bounds || !finite(Number(bounds.left)) || !finite(Number(bounds.right)) || !finite(Number(bounds.top)) || !finite(Number(bounds.bottom))) return clampZoom(existing);
  const viewportWidth = Number(bounds.right) - Number(bounds.left), viewportHeight = Number(bounds.bottom) - Number(bounds.top);
  const current = row && matrix(row.viewTransform), scale = current ? Math.max(Math.hypot(current[0], current[1]), Math.hypot(current[2], current[3])) : 0;
  if (!(viewportWidth > 0 && viewportHeight > 0 && scale > 0)) return clampZoom(existing);
  const visibleWidth = viewportWidth / scale, visibleHeight = viewportHeight / scale;
  const factor = Math.min(visibleWidth / (region.width * 1.35), visibleHeight / (region.height * 1.35));
  return clampZoom(existing * (Number.isFinite(factor) && factor > 0 ? factor : 1));
}

function verifyNative(row, expected, region) {
  if (!row || !row.viewTransform) return { ok: false, reason: 'VIEW_TRANSFORM_UNAVAILABLE' };
  const center = viewportCenter(row);
  if (!center) return { ok: false, reason: 'VIEWPORT_CENTER_UNAVAILABLE' };
  const target = regionCenter(region);
  const tolerance = Math.max(16, Math.max(region.width, region.height) * 0.2);
  return { ok: closeEnough(center, target, tolerance), center, target, tolerance,
    zoom: expected, reason: closeEnough(center, target, tolerance) ? null : 'VIEW_FOCUS_READBACK_MISMATCH' };
}

async function setDomView(view, center, zoom) {
  if (!view) return { attempted: false, supported: false };
  const hasZoom = (() => { try { return 'zoom' in view || typeof view.setZoom === 'function'; } catch (_) { return false; } })();
  const hasCenter = (() => { try { return 'center' in view || 'centerPoint' in view || typeof view.setCenter === 'function'; } catch (_) { return false; } })();
  if (!hasZoom && !hasCenter) return { attempted: false, supported: false };
  try {
    if (typeof view.setZoom === 'function') await view.setZoom(zoom);
    else if (hasZoom) view.zoom = zoom;
    if (typeof view.setCenter === 'function') await view.setCenter(center);
    else if ('center' in view) {
      try { view.center = { x: center.x, y: center.y }; }
      catch (_) { view.center = [center.x, center.y]; }
    } else if ('centerPoint' in view) {
      try { view.centerPoint = { x: center.x, y: center.y }; }
      catch (_) { view.centerPoint = [center.x, center.y]; }
    }
    const read = readDomView(view);
    const centerOk = !hasCenter || (read && closeEnough(read.center, center, Math.max(16, Math.max(Math.abs(center.x), Math.abs(center.y)) * 0.002)));
    const zoomOk = !hasZoom || (read && read.zoom !== null && Math.abs(read.zoom - zoom) <= Math.max(1, zoom * 0.02));
    return { attempted: true, supported: !!(centerOk && zoomOk), read };
  } catch (error) { return { attempted: true, supported: false, error }; }
}

async function setBatchPlayView(app, docId, center, zoom) {
  if (!app || typeof app.batchPlay !== 'function') return { attempted: false, supported: false };
  // The descriptor is intentionally isolated here. Photoshop builds that do
  // not expose a writable view descriptor reject it; the caller then returns
  // VIEW_FOCUS_UNSUPPORTED instead of claiming a successful navigation.
  const descriptor = { _obj: 'zoom', _target: [{ _ref: 'document', _id: docId }],
    to: { _unit: 'percentUnit', _value: zoom },
    center: { _obj: 'point', horizontal: { _unit: 'pixelsUnit', _value: center.x }, vertical: { _unit: 'pixelsUnit', _value: center.y } } };
  try {
    const result = await app.batchPlay([descriptor], { synchronousExecution: true, modalBehavior: 'execute' });
    if (result && result[0] && result[0]._obj === 'error') return { attempted: true, supported: false, error: result[0] };
    return { attempted: true, supported: true, descriptor };
  } catch (error) { return { attempted: true, supported: false, error }; }
}

function createViewFocus({ app, core, now = () => Date.now(), viewState = null, adapter = null }) {
  async function focus(params = {}) {
    const timestamp = now();
    if (viewState && adapter && app && app.activeDocument && params.docId != null
      && Number(app.activeDocument.id) !== Number(params.docId)) {
      throw failure('VIEW_DOCUMENT_NOT_ACTIVE', '目标 Photoshop 文档未能切换为当前文档');
    }
    const input = Object.assign({}, params);
    // The adapter contract already receives the active document object. Fill
    // omitted metadata from that object for the local capability probe, while
    // the real bridge path still requires the desktop snapshot to provide all
    // document identity fields.
    if (viewState && adapter) {
      if (input.candidateId == null) input.candidateId = 'candidate:adapter';
      if (input.expiresAt == null) input.expiresAt = timestamp + 240000;
      const active = app && app.activeDocument;
      if (active) {
        if (input.docName == null && Number(input.docId) === Number(active.id)) input.docName = String(active.name || '');
        if (input.docWidth == null && Number(input.docId) === Number(active.id)) input.docWidth = Number(active.width);
        if (input.docHeight == null && Number(input.docId) === Number(active.id)) input.docHeight = Number(active.height);
        if (input.historyId == null && Number(input.docId) === Number(active.id)) input.historyId = historyId(active);
      }
    }
    const normalized = normalizeParams(input, timestamp);
    const requested = documentById(app, normalized.docId);
    if (!requested) {
      if (app && app.activeDocument && Number(app.activeDocument.id) !== normalized.docId) throw failure('VIEW_DOCUMENT_NOT_ACTIVE', '目标 Photoshop 文档未能切换为当前文档');
      throw failure('SOURCE_DOCUMENT_CLOSED', '目标 Photoshop 文档已关闭，请重新执行检测');
    }
    const size = dimensions(requested);
    if (normalized.docWidth && (!size || size.width !== normalized.docWidth || size.height !== normalized.docHeight)) throw failure('VIEW_DOCUMENT_CHANGED', '画布尺寸已经变化，请重新执行 AI 修图痕迹检测');
    if (normalized.docName && String(requested.name || '') !== normalized.docName) throw failure('VIEW_DOCUMENT_CHANGED', '文档名称已经变化，请重新执行 AI 修图痕迹检测');
    // The injected adapter path is used by the production capability probe and
    // tests. It still checks document identity and preserves the document
    // history/selection state around the adapter call.
    if (viewState && adapter && typeof viewState === 'function' && typeof adapter.focus === 'function') {
      if (!app.activeDocument || Number(app.activeDocument.id) !== normalized.docId) throw failure('VIEW_DOCUMENT_NOT_ACTIVE', '目标 Photoshop 文档未能切换为当前文档');
      const beforeState = await viewState({ docId: normalized.docId, expiresAt: normalized.expiresAt });
      if (beforeState && beforeState.activeDocumentBound === false) throw failure('VIEW_DOCUMENT_NOT_ACTIVE', '目标 Photoshop 文档未能切换为当前文档');
      if (normalized.expiresAt <= now()) throw failure('VIEW_FOCUS_EXPIRED', '候选定位请求已过期，请重新执行 AI 修图痕迹检测');
      const beforeHistory = historyId(requested);
      const viewport = beforeState && beforeState.bounds ? beforeState : { zoomPercent: currentZoom(requested) || 100, bounds: null };
      const center = regionCenter(normalized.region), zoom = desiredZoom({ zoomPercent: viewport.zoomPercent || currentZoom(requested) || 100, bounds: viewport.bounds }, normalized.region, normalized.mode);
      const modalRun = async () => adapter.focus({ doc: requested, app, candidateId: normalized.candidateId,
        region: normalized.region, center, zoomPercent: zoom, mode: normalized.mode,
        docId: normalized.docId, historyId: normalized.historyId });
      let adapterResult;
      try {
        adapterResult = await core.executeAsModal(modalRun, { commandName: '定位到 AI 修图痕迹候选' });
      } catch (error) { throw error; }
      if (normalized.expiresAt <= now()) throw failure('VIEW_FOCUS_EXPIRED', '候选定位请求已过期，请重新执行 AI 修图痕迹检测');
      const afterHistory = historyId(requested);
      if (beforeHistory !== afterHistory) throw failure('VIEW_FOCUS_STATE_CHANGED', '定位操作改变了 Photoshop 文档历史状态，已拒绝确认成功');
      const afterState = await viewState({ docId: normalized.docId, expiresAt: normalized.expiresAt });
      if (afterState && afterState.activeDocumentBound === false) throw failure('VIEW_FOCUS_STATE_CHANGED', '定位操作改变了当前 Photoshop 文档');
      if (adapterResult && adapterResult.focused === false) throw failure('VIEW_FOCUS_UNSUPPORTED', 'Photoshop 没有确认画布已经移动到目标区域');
      return { ok: true, focused: true, candidateId: normalized.candidateId, analysisId: input.analysisId || null,
        coordinateSpace: 'document-pixels', region: normalized.region, center, zoomPercent: zoom,
        selectionChanged: false, layersChanged: false, historyIdUnchanged: true,
        precision: adapterResult && adapterResult.precision || 'adapter', adapter: adapterResult || null };
    }
    const currentHistory = historyId(requested);
    if (currentHistory == null) throw failure('VIEW_FOCUS_HISTORY_UNAVAILABLE', '当前 Photoshop 无法确认文档版本，已停止定位');
    if (currentHistory !== normalized.historyId) throw failure('VIEW_FOCUS_STALE', '检测之后画面已经发生变化，请重新执行 AI 修图痕迹检测');
    if (!app.activeDocument || Number(app.activeDocument.id) !== normalized.docId) {
      if (!core || typeof core.executeAsModal !== 'function' || typeof app.batchPlay !== 'function') throw failure('VIEW_FOCUS_UNSUPPORTED', '当前 Photoshop 不支持安全切换目标文档');
      await core.executeAsModal(async () => { await app.batchPlay([{ _obj: 'select', _target: [{ _ref: 'document', _id: normalized.docId }] }], {}); }, { commandName: '定位 AI 修图痕迹候选' });
    }
    if (!app.activeDocument || Number(app.activeDocument.id) !== normalized.docId) throw failure('VIEW_DOCUMENT_NOT_ACTIVE', '目标 Photoshop 文档未能切换为当前文档');
    const beforeGuard = await guardState(app, requested, normalized.docId);
    if (!beforeGuard.activeDocumentBound) throw failure('VIEW_DOCUMENT_NOT_ACTIVE', '目标 Photoshop 文档未能切换为当前文档');
    if (normalized.historyId !== null && beforeGuard.historyId !== null && beforeGuard.historyId !== normalized.historyId) {
      throw failure('VIEW_FOCUS_STALE', '检测之后 Photoshop 画面已经变化，请重新执行 AI 修图痕迹检测');
    }
    const before = await nativeViewRead(app, normalized.docId);
    const center = regionCenter(normalized.region), zoom = desiredZoom({ doc: requested, row: before, region: normalized.region, mode: normalized.mode });
    let changed = null;
    const view = getView(requested, app);
    if (view) changed = await setDomView(view, center, zoom);
    if (!changed || !changed.supported) changed = await setBatchPlayView(app, normalized.docId, center, zoom);
    if (!changed || !changed.supported) throw failure('VIEW_FOCUS_UNSUPPORTED', '当前 Photoshop 版本没有可验证的画布自动定位能力', changed && changed.error);
    const after = await nativeViewRead(app, normalized.docId);
    const verified = verifyNative(after, zoom, normalized.region);
    // Some hosts expose a writable DOM view but do not expose a native matrix
    // for readback. In that case we only trust an explicit DOM readback.
    const domRead = readDomView(view);
    const domVerified = domRead && domRead.center && closeEnough(domRead.center, center, Math.max(16, Math.max(normalized.region.width, normalized.region.height) * 0.2));
    if (!verified.ok && !domVerified) throw failure('VIEW_FOCUS_UNSUPPORTED', 'Photoshop 未确认画布已经移动到目标区域');
    const afterGuard = await guardState(app, requested, normalized.docId);
    if (!afterGuard.activeDocumentBound) throw failure('VIEW_FOCUS_STATE_CHANGED', '定位期间 Photoshop 活动文档发生变化');
    const historyIdUnchanged = beforeGuard.historyId === null || afterGuard.historyId === null
      ? null : beforeGuard.historyId === afterGuard.historyId;
    const layersChanged = !equalIds(beforeGuard.layerIds, afterGuard.layerIds);
    const selectionChanged = beforeGuard.selectionState.available && afterGuard.selectionState.available
      ? !sameRect(beforeGuard.selectionState.value, afterGuard.selectionState.value) : null;
    if (historyIdUnchanged === false || layersChanged || selectionChanged === true) {
      throw failure('VIEW_FOCUS_STATE_CHANGED', '定位期间 Photoshop 文档状态发生变化，已停止使用本次结果');
    }
    return { ok: true, focused: true, candidateId: normalized.candidateId, docId: normalized.docId,
      docName: normalized.docName, region: normalized.region, center, zoomAfter: domRead && domRead.zoom || zoom,
      verification: verified.ok ? 'native-readback' : 'dom-readback', selectAnnotationLayer: false,
      annotationLayerRequested: normalized.selectAnnotationLayer, historyIdUnchanged,
      selectionChanged, layersChanged };
  }
  return { focus };
}

module.exports = {
  candidateId, rectangle, normalizeRect, normalizeMode, normalizeParams, regionCenter, desiredZoom,
  createViewFocus, failure
};
