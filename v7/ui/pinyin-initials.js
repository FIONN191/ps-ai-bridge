  // 原理: 中文排序(collation)默认按拼音走, 所以拿一串"每个字母的第一个字"当尺子,
  //       二分找出目标字落在哪两把尺子之间, 就知道它的首字母。
  // ⚠ 这依赖运行环境的中文排序真的按拼音 —— 所以下面有自检, 不过就整个关掉。
